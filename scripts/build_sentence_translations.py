"""Build offline Korean sentence lookup; --translate fetches missing public examples."""
import argparse
import concurrent.futures
import json
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "content/illustrated-vocabulary/examples_ko.json"
def translate(items):
    query = "\n".join(sentence for _, sentence in items)
    url = "https://translate.googleapis.com/translate_a/single?" + urllib.parse.urlencode(
        dict(client="gtx", sl="en", tl="ko", dt="t", q=query))
    for attempt in range(4):
        try:
            result = json.load(urllib.request.urlopen(url, timeout=30))
            lines = "".join(part[0] or "" for part in result[0]).strip().splitlines()
            if len(lines) != len(items):
                if len(items) == 1: raise ValueError("translation line mismatch")
                return dict(pair for item in items for pair in translate([item]).items())
            return {word: {"en": source, "ko": target.strip()} for (word, source), target in zip(items, lines)}
        except Exception:
            if attempt == 3: raise
            time.sleep(2 ** attempt)

def key(text):
    value = 14695981039346656037
    for byte in text.encode(): value = ((value ^ byte) * 1099511628211) & ((1 << 64) - 1)
    return value or 1

def main():
    parser = argparse.ArgumentParser(); parser.add_argument("--translate", action="store_true")
    args = parser.parse_args()
    examples = json.loads((DATA.parent / "examples.json").read_text(encoding="utf-8"))
    saved = json.loads(DATA.read_text(encoding="utf-8")) if DATA.exists() else {}
    missing = [(word, text) for word, text in examples.items() if saved.get(word, {}).get("en") != text]
    if missing and not args.translate: raise SystemExit("Missing translations; use --translate")
    with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
        for result in pool.map(translate, [missing[i:i+15] for i in range(0, len(missing), 15)]):
            saved.update(result)
    fixes = {
        "pencil": "나는 연필로 필기를 해요.", "eraser": "지우개로 잘못 쓴 글자를 지웠어요.",
        "ruler": "자로 선을 그리세요.", "crayon box": "그녀는 크레용을 크레용 상자에 보관해요.",
        "glue stick": "풀로 종이를 붙이세요."
    }
    for word, text in fixes.items(): saved[word] = {"en": examples[word], "ko": text}
    saved = {word: saved[word] for word in examples}
    for item in saved.values():
        item["ko"] = item["ko"].replace("\u200b", "")
        assert all(32 <= ord(ch) <= 126 or '\uac00' <= ch <= '\ud7a3' for ch in item["ko"]), "Unsupported translation glyph"
    DATA.write_text(json.dumps(saved, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    entries = sorted((key(item["en"]), item["ko"]) for item in saved.values())
    assert len({item[0] for item in entries}) == len(entries), "Sentence hash collision"
    assert all(any('\uac00' <= ch <= '\ud7a3' for ch in target) for _, target in entries)
    lines = ['// Generated by scripts/build_sentence_translations.py; public example translations.',
             '#pragma once', '#include "cache_policy.hpp"', 'namespace wordmon {',
             'inline const char* sentenceTranslation(const char* sentence) {',
             '  struct Entry { uint64_t key; const char* text; };', '  static const Entry entries[] = {']
    lines += [f'    {{0x{value:016x}ULL, {json.dumps(target, ensure_ascii=False)}}},' for value, target in entries]
    lines += ['  };', '  const uint64_t target = assetKey(sentence);',
              '  size_t first = 0, last = sizeof(entries)/sizeof(entries[0]);',
              '  while(first < last) { const size_t mid=(first+last)/2;',
              '    if(entries[mid].key < target) first=mid+1; else last=mid; }',
              '  return first < sizeof(entries)/sizeof(entries[0]) && entries[first].key==target ? entries[first].text : "";',
              '}', '}']
    (ROOT / "include/sentence_translations.hpp").write_text("\n".join(lines)+"\n", encoding="utf-8")
    print(f"Built {len(entries)} offline sentence translations")
if __name__ == "__main__": main()
