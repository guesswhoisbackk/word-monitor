"""Generate an offline quiz bank and exact-match corrections for cached old decks."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "content/illustrated-vocabulary"


def main():
    words = json.loads((DATA / "unique_words.json").read_text(encoding="utf-8"))
    corrections = json.loads((DATA / "corrections.json").read_text(encoding="utf-8"))
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    assert len({w["word"] for w in words}) == len(words)
    assert all(w["word"] and w["ko"].strip() for w in words)
    lines = ['// Generated by scripts/build_quiz_content.py', '#pragma once',
             '#include <cstdint>', '#include <cstring>', 'namespace wordmon {',
             'struct QuizWord { const char* word; const char* meaning; };',
             'static const QuizWord kQuizWords[] = {']
    lines += ['  {' + quote(w['word']) + ', ' + quote(w['ko']) + '},' for w in words]
    lines += ['};', 'constexpr uint16_t kQuizWordCount = sizeof(kQuizWords)/sizeof(kQuizWords[0]);', '}']
    (ROOT / 'include/quiz_content.hpp').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    lines = ['// Generated by scripts/build_quiz_content.py', '#pragma once',
             '#include <cstring>', 'namespace wordmon {']
    for field in ('meaning', 'example'):
        lines += [f'inline const char* corrected{field.title()}(const char* word, const char* original) {{',
                  '  struct Correction { const char* word; const char* oldText; const char* newText; };',
                  '  static const Correction entries[] = {']
        lines += ['    {'+', '.join(quote(x) for x in (w,c['old_'+field],c[field]))+'},'
                  for w,c in corrections.items() if field in c]
        lines += ['  };', '  for(const auto& entry : entries)',
                  '    if(!strcmp(word,entry.word) && !strcmp(original,entry.oldText)) return entry.newText;',
                  '  return original;', '}']
    lines += ['}']
    (ROOT / 'include/content_corrections.hpp').write_text('\n'.join(lines)+'\n', encoding='utf-8')
    print(f'Built {len(words)} quiz words and {len(corrections)} corrected entries')


if __name__ == '__main__':
    main()
